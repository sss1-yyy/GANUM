/** 문자열이 16유형 중 하나인지 */
export function isMbtiCode(value: string | undefined): value is MbtiCode {
  return value !== undefined && value in MBTI_RESULTS;
}

/** 같은 캐릭터에 속한 4글자 유형들 (예: 도전형 → ESFJ, ESFP, ENFJ, ENFP) */
export function codesOfType(type: InvestmentType): MbtiCode[] {
  return (Object.keys(MBTI_RESULTS) as MbtiCode[]).filter(
    (code) => MBTI_RESULTS[code].type === type,
  );
}
